#include <iostream>

using namespace std;

int main()
{
    // while loop
    int b = 0;
    while (b < 10)
    {
        cout << b << endl;
        b++;
    }

    // for loop
    for (int i = 0; i < 10; i++)
    {
        cout << i << endl;
    }

    // do while loop
    int a = 0;
    do
    {
        cout << a << endl;
    } while (a != 0);
}
